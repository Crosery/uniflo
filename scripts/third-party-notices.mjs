#!/usr/bin/env node
// Regenerate the Rust-crate section of THIRD_PARTY_NOTICES.md from `cargo metadata`: every crate
// compiled into the `uniflo` binary (normal dependencies, any target platform) with its license
// and the license texts it ships, identical texts listed once. Only the text between the markers
// is touched; other sections of the file (web demo assets…) are left as they are.
//   node scripts/third-party-notices.mjs           # rewrite the section
//   node scripts/third-party-notices.mjs --check   # exit 1 when it is out of date (verify.sh)
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const file = join(root, "THIRD_PARTY_NOTICES.md");
const BEGIN = "<!-- BEGIN rust-crates: generated by scripts/third-party-notices.mjs, do not edit by hand -->";
const END = "<!-- END rust-crates -->";
const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)/i;

const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], { cwd: root, maxBuffer: 1 << 28 }),
);
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const start = meta.packages.find((p) => p.name === "uniflo" && p.source === null).id;
const seen = new Set();
const stack = [start];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const d of nodes.get(id).deps) if (d.dep_kinds.some((k) => k.kind === null)) stack.push(d.pkg);
}
const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const crates = [...seen]
  .map((id) => byId.get(id))
  .filter((p) => p.source !== null)
  .sort((a, b) => cmp(a.name, b.name) || cmp(a.version, b.version));

const texts = new Map(); // sha256 → { name, text, users[] }
const withoutText = [];
for (const p of crates) {
  const dir = dirname(p.manifest_path);
  const names = readdirSync(dir)
    .filter((n) => LICENSE_FILE.test(n) && statSync(join(dir, n)).isFile())
    .sort(cmp);
  if (!names.length) withoutText.push(p);
  for (const n of names) {
    const text = readFileSync(join(dir, n), "utf8").replace(/\r\n?/g, "\n").replace(/\s+$/, "");
    const key = createHash("sha256").update(text).digest("hex");
    if (!texts.has(key)) texts.set(key, { name: n, text, users: [] });
    texts.get(key).users.push(`${p.name} ${p.version}`);
  }
}

const out = [BEGIN, "", "## Rust crates", ""];
out.push(
  `The \`uniflo\` executable statically links the ${crates.length} crates below (any target platform; ` +
    "generated from `cargo metadata`). `libsqlite3-sys` bundles SQLite, which is in the public domain.",
  "",
  "| crate | version | license | source |",
  "|---|---|---|---|",
);
for (const p of crates) {
  const src = p.repository || `https://crates.io/crates/${p.name}`;
  out.push(`| ${p.name} | ${p.version} | ${(p.license || p.license_file || "?").replace(/\|/g, "\\|")} | ${src} |`);
}
out.push("", "### License texts", "");
if (withoutText.length) {
  out.push(
    `These crates ship no license file; their declared license applies as published: ${withoutText
      .map((p) => `${p.name} ${p.version} (${p.license})`)
      .join(", ")}.`,
    "",
  );
}
for (const t of [...texts.values()].sort((a, b) => cmp(a.users[0], b.users[0]) || cmp(a.name, b.name))) {
  out.push(`#### ${t.name} — ${t.users.join(", ")}`, "", "````text", t.text, "````", "");
}
out.push(END);
const section = out.join("\n");

const current = existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n?/g, "\n") : "";
const [b, e] = [current.indexOf(BEGIN), current.indexOf(END)];
const next =
  b >= 0 && e > b
    ? current.slice(0, b) + section + current.slice(e + END.length)
    : `${current.replace(/\s*$/, "")}${current.trim() ? "\n\n" : ""}${section}\n`;

if (process.argv.includes("--check")) {
  if (next !== current) {
    console.error("THIRD_PARTY_NOTICES.md is out of date: run `node scripts/third-party-notices.mjs`");
    process.exit(1);
  }
  console.log(`third-party notices: ${crates.length} crates, ${texts.size} license texts, up to date`);
} else {
  writeFileSync(file, next);
  console.log(`third-party notices: ${crates.length} crates, ${texts.size} license texts written`);
}
